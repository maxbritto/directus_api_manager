import 'dart:io';

import 'package:directus_api_manager/src/generator/directus_schema_fetcher.dart';
import 'package:directus_api_manager/src/generator/entity_class_generator.dart';
import 'package:directus_api_manager/src/generator/generator_config.dart';

/// CLI entry point for the Directus entity generator.
///
/// Usage:
///   dart run directus_api_manager:generate --url http://localhost:8055 --token YOUR_TOKEN
Future<void> main(List<String> args) async {
  final GeneratorConfig config;
  try {
    config = GeneratorConfig.fromArgs(args);
  } on ArgumentError catch (e) {
    stderr.writeln("Error: ${e.message}");
    stderr.writeln("Use --help for usage information.");
    exit(1);
  } catch (_) {
    // Help was requested
    exit(0);
  }

  print("Directus Entity Generator");
  print("Connecting to: ${config.directusUrl}");

  final fetcher = DirectusSchemaFetcher(
    baseUrl: config.directusUrl,
    staticToken: config.staticToken,
  );

  // Authenticate if using email/password
  if (config.staticToken == null &&
      config.email != null &&
      config.password != null) {
    print("Authenticating with email/password...");
    try {
      await fetcher.authenticate(
          email: config.email!, password: config.password!);
      print("Authentication successful.");
    } catch (e) {
      stderr.writeln("Authentication failed: $e");
      exit(1);
    }
  }

  // Fetch collections
  print("Fetching collections...");
  final List<DirectusCollectionInfo> collections;
  try {
    collections = await fetcher.fetchCollections();
  } catch (e) {
    stderr.writeln("Failed to fetch collections: $e");
    exit(1);
  }

  // Filter collections based on config
  final filteredCollections = collections.where((c) {
    if (config.excludeCollections.contains(c.collection)) return false;
    if (config.includeCollections != null &&
        !config.includeCollections!.contains(c.collection)) {
      return false;
    }
    return true;
  }).toList();

  if (filteredCollections.isEmpty) {
    print("No collections found to generate.");
    exit(0);
  }

  print(
      "Found ${filteredCollections.length} collection(s) to generate: ${filteredCollections.map((c) => c.collection).join(', ')}");

  // Fetch relations
  print("Fetching relations...");
  final List<DirectusRelationInfo> relations;
  try {
    relations = await fetcher.fetchRelations();
  } catch (e) {
    stderr.writeln("Failed to fetch relations: $e");
    exit(1);
  }

  final generator = EntityClassGenerator(
    classSuffix: config.classSuffix,
    generateReadonlySetters: config.generateReadonlySetters,
  );

  // Ensure output directory exists
  if (!config.dryRun) {
    final outputDir = Directory(config.outputDirectory);
    if (!outputDir.existsSync()) {
      outputDir.createSync(recursive: true);
      print("Created output directory: ${config.outputDirectory}");
    }
  }

  // Generate each collection
  int generatedCount = 0;
  for (final collection in filteredCollections) {
    print("  Generating ${collection.collection}...");

    final List<DirectusFieldInfo> fields;
    try {
      fields = await fetcher.fetchFieldsForCollection(collection.collection);
    } catch (e) {
      stderr.writeln(
          "  Warning: Failed to fetch fields for ${collection.collection}: $e");
      continue;
    }

    final source = generator.generateClassFile(
      collection: collection,
      fields: fields,
      relations: relations,
    );

    final fileName = generator.generateFileName(collection.collection);

    if (config.dryRun) {
      print("--- $fileName ---");
      print(source);
      print("--- end ---");
    } else {
      final filePath = "${config.outputDirectory}/$fileName";
      final file = File(filePath);

      // Safety check: do not overwrite files that were not generated by us
      if (file.existsSync()) {
        final existingContent = file.readAsStringSync();
        if (!existingContent
            .startsWith(EntityClassGenerator.generatedFileHeader)) {
          stderr.writeln(
              "  Skipping $fileName: file exists and was not generated by this tool.");
          continue;
        }
      }

      file.writeAsStringSync(source);
      print("  Written: $filePath");
    }
    generatedCount++;
  }

  print(
      "\nDone! Generated $generatedCount file(s)${config.dryRun ? " (dry run)" : ""}.");

  if (!config.dryRun && generatedCount > 0) {
    print(
        "\nNext steps:");
    print(
        "  1. Add an import for each generated file in your main file");
    print(
        "  2. Run: dart run build_runner build");
    print(
        "  3. Call initializeReflectable() in your main() function");
  }
}
